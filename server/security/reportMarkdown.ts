import type { Finding } from "../../drizzle/schema";

function section(value: string | null | undefined, fallback = "Not recorded.") {
  return value?.trim() || fallback;
}

export function composeBugBountyMarkdown(finding: Finding) {
  const evidence = Array.isArray(finding.evidenceMetadata) && finding.evidenceMetadata.length
    ? finding.evidenceMetadata.map((item: unknown) => {
      const entry = item as { label?: string; kind?: string; reference?: string };
      return `- **${entry.label || "Evidence"}** (${entry.kind || "reference"}): ${entry.reference || "Not recorded"}`;
    }).join("\n")
    : "- No evidence metadata was attached.";
  return `# ${finding.title}

> **Severity:** ${finding.severity.toUpperCase()}  
> **CVSS:** ${finding.cvssScore ?? "Not scored"}  
> **Lifecycle:** ${finding.status.replaceAll("_", " ")}

## Executive summary

${section(finding.impact)}

## Authorized test environment

${section(finding.testEnvironment, "Record the authorized environment, scope reference, and test date before sharing this report.")}

## Safe reproduction narrative

${section(finding.safePoc, "Use a redacted, non-destructive narrative only. Do not include credentials, secrets, exploit automation, or production personal data.")}

## Security impact

${section(finding.impact)}

## Recommended remediation

${section(finding.remediation, "Document an implementation-specific remediation and validation plan.")}

## Re-test notes

${section(finding.retestNotes, "Re-test has not been recorded.")}

## Evidence index

${evidence}

---

*Generated by AegisScope from a private, in-scope finding. Verify all content and remove sensitive material before disclosure.*
`;
}
